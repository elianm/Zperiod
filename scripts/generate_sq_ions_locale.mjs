function translateText(text) {
  if (EXACT.has(text)) return EXACT.get(text);
  if (DIRECT_NAMES.has(text)) return DIRECT_NAMES.get(text);
  let out = text;
  for (const [en, sq] of REPLACEMENTS.sort((a, b) => b[0].length - a[0].length)) {
    out = out.split(en).join(sq);
  }
  return out;
}

function splitList(value) {
  return String(value || "")
    .split(";")
    .map((item) => item.trim())
    .filter(Boolean);
}

function parseKeyCompounds(value) {
  return String(value || "")
    .split(", ")
    .map((item) => {
      const match = item.match(/^(.+) \((.+)\)$/);
      if (match) return { formula: match[1], name: translateText(match[2]) };
      return { formula: item, name: "" };
    });
}

